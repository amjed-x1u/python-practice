# Madlib Game
# A word game where you create a story
# by filling in the blanks with your own words

place = input("Enter a place :")
someone = input("Enter a person's name: ")
pronoun = input("Enter a pronoun (her/him/them):")

# Print the story
print("--- YOUR STORY ---")
print(f"Today, like every day, I went to study in {place}.")
print(f"And I saw {someone}.")
print(f"Every time I see {someone}, I feel a quiet kind of motivation.")
print(f"I just enjoyed watching {pronoun} (^///^).")
print(f"If someday you read this, I think you will know it's about you.")
print(f"--- END OF THE STORY ---")
